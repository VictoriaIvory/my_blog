def env_flag(name, default=False):
    """把 .env 里的 '1/true/yes/on' 读成布尔值。"""
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in ('1', 'true', 'yes', 'on')


